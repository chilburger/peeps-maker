// Converts the @opeepsfun/open-peeps part files (CC0 art by Pablo Stanley) and the
// DiceBear Open Peeps masks into plain SVG strings with {{color}} tokens.
// The source files are parsed as text; none of their code is executed.
// Usage: node tools/extract-parts.mjs <opeepsfun pkg dir> <dicebear pkg dir> > parts/parts.js
import fs from 'node:fs';
import path from 'node:path';

const [opDir, dbDir] = process.argv.slice(2);
const attrName = (k) => (k === 'viewBox' ? k : k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase()));
const esc = (v) => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;');

// Minimal parser for: React.createElement("tag", { k: 'v', k2: ident }, child, child)
function parseCalls(src, vars) {
  let i = 0;
  const ws = () => { while (/\s/.test(src[i])) i++; };
  const expect = (s) => { ws(); if (!src.startsWith(s, i)) throw new Error(`expected ${s} at ${i}: ${src.slice(i, i + 40)}`); i += s.length; };
  const str = () => {
    ws(); const q = src[i++]; let out = '';
    while (src[i] !== q) { if (src[i] === '\\') { out += src[i + 1]; i += 2; } else out += src[i++]; }
    i++; return out;
  };
  const ident = () => { ws(); const m = /^[A-Za-z_$][\w$.]*/.exec(src.slice(i)); i += m[0].length; return m[0]; };
  const value = () => {
    ws();
    if (src[i] === '"' || src[i] === "'") return str();
    if (/[\d.-]/.test(src[i])) { const m = /^-?[\d.]+/.exec(src.slice(i)); i += m[0].length; return m[0]; }
    const id = ident();
    if (!(id in vars)) throw new Error('unknown identifier ' + id);
    return vars[id];
  };
  const element = () => {
    expect('React.createElement(');
    ws();
    let tag;
    if (src.startsWith('React.Fragment', i)) { i += 'React.Fragment'.length; tag = null; }
    else tag = str();
    expect(',');
    ws();
    const attrs = {};
    if (src.startsWith('null', i)) i += 4;
    else {
      expect('{');
      for (;;) {
        ws(); if (src[i] === '}') { i++; break; }
        ws();
        const k = src[i] === '"' || src[i] === "'" ? str() : ident(); expect(':'); attrs[k] = value(); ws();
        if (src[i] === ',') i++;
      }
    }
    const kids = [];
    for (;;) {
      ws();
      if (src[i] === ')') { i++; break; }
      expect(','); ws();
      if (src[i] === ')') { i++; break; }
      kids.push(element());
    }
    const inner = kids.join('');
    if (tag === null) return inner;
    const a = Object.entries(attrs).map(([k, v]) => ` ${attrName(k)}="${esc(v)}"`).join('');
    return `<${tag}${a}>${inner}</${tag}>`;
  };
  const start = src.indexOf('return (React.createElement(');
  if (start < 0) throw new Error('no render body');
  i = start + 'return ('.length;
  return element();
}

function load(file) {
  const src = fs.readFileSync(file, 'utf8');
  const cfgM = /Config = (\{[\s\S]*?\n\});/.exec(src);
  const cfgText = cfgM[1];
  const name = /name: "([^"]+)"/.exec(cfgText)[1];
  const props = [...cfgText.matchAll(/name: "(\w+Color)"/g)].map((m) => m[1]);
  const num = (k) => Number(new RegExp(k + ': ([\\d.]+)').exec(cfgText)?.[1]);
  const viewBox = /viewBox: "([^"]+)"/.exec(cfgText)?.[1];
  // Local variable names bound to each prop, eg `_b = _a.skinColor, skinColor = ...`
  const vars = {};
  for (const m of src.matchAll(/_\w+ = _a\.(\w+), (\w+) = _\w+ === void 0/g)) vars[m[2]] = `{{${m[1]}}}`;
  return {
    name, w: num('width'), h: num('height'), viewBox,
    colors: props.filter((p) => p !== 'outlineColor'),
    svg: parseCalls(src, vars),
  };
}

function dir(sub) {
  const d = path.join(opDir, 'build', sub);
  const out = {};
  for (const f of fs.readdirSync(d).sort()) {
    if (!f.endsWith('.js') || f === 'index.js') continue;
    out[f.replace(/\.js$/, '')] = load(path.join(d, f));
  }
  return out;
}

const parts = {
  hair: dir('head'),
  face: dir('face'),
  beard: dir('beard'),
  accessory: dir('accessory'),
  bust: dir('body/effigy'),
  standing: dir('body/standing'),
  sitting: dir('body/sitting'),
};

// DiceBear masks are template literals: key: (components, colors) => `<svg markup>`
const maskSrc = fs.readFileSync(path.join(dbDir, 'lib/components/mask.js'), 'utf8');
parts.mask = {};
for (const m of maskSrc.matchAll(/(\w+): \(components, colors\) => `([^`]*)`/g)) {
  if (m[2].includes('${')) throw new Error('mask ' + m[1] + ' has interpolation');
  parts.mask[m[1]] = { name: m[1].replace(/([A-Z])/g, ' $1').replace(/^./, (c) => c.toUpperCase()), svg: m[2] };
}

process.stdout.write('// Generated by tools/extract-parts.mjs. Art: Open Peeps by Pablo Stanley, CC0 1.0.\n');
process.stdout.write('window.PEEP_PARTS = ' + JSON.stringify(parts) + ';\n');
