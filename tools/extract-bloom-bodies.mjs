// Adds head-and-shoulders outfits that @opeepsfun/open-peeps leaves out (Tee 2, Device,
// Sweater), taken from the Open Peeps "Flat Assets" pack (CC0, Pablo Stanley) as tagged in
// BLOOM's openpeeps-parts.json: #ff00f0 = skin, #ff00f2 = clothing, #1A1A1A = ink.
// The outfits are shifted so their top edge sits at y=0, matching the other bust outfits.
// Usage: node tools/extract-bloom-bodies.mjs <openpeeps-parts.json> > parts/extra-bodies.js
import fs from 'node:fs';

const WANT = { 'Tee-2': 'TeeTwo', Device: 'Device', Sweater: 'Sweater' };
// top edge (y) and right edge of each outfit's artwork, measured with getBBox()
const BOX = { 'Tee-2': [-39, 816.4], Device: [-33, 794.7], Sweater: [-49.4, 852.4] };
const HEIGHT = { 'Tee-2': 758.4, Device: 742.1, Sweater: 781.6 };

const data = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const out = {};
for (const b of data.parts.body) {
  const id = WANT[b.id];
  if (!id) continue;
  const inner = b.svg.replace(/^<g transform="[^"]*">/, '').replace(/<\/g>\s*$/, '');
  const [top, right] = BOX[b.id];
  const svg = `<g transform="translate(0 ${-top})">${inner}</g>`
    .replace(/#ff00f0/gi, '{{skinColor}}')
    .replace(/#ff00f2/gi, '{{topColor}}')
    .replace(/#1A1A1A/gi, '{{outlineColor}}');
  if (/<script|on\w+=/i.test(svg)) throw new Error('unexpected markup in ' + b.id);
  const w = Math.ceil(Math.max(818, right)), h = Math.ceil(HEIGHT[b.id]);
  out[id] = { name: b.name, w, h, viewBox: `0 0 ${w} ${h}`, colors: ['skinColor', 'topColor'], svg };
}
process.stdout.write('// Generated by tools/extract-bloom-bodies.mjs. Art: Open Peeps by Pablo Stanley, CC0 1.0.\n');
process.stdout.write('Object.assign(window.PEEP_PARTS.bust, ' + JSON.stringify(out) + ');\n');
